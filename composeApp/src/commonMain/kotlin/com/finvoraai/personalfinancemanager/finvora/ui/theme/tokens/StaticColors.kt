package com.finvoraai.personalfinancemanager.finvora.ui.theme.tokens

import androidx.compose.ui.graphics.Color

/**
 * Pure, raw color tokens that do not change based on the active theme (Dark/Light).
 * Use these when you need an absolute color value (like Black for shadows or White for static overlays).
 */
object StaticColors {
    val Black = Color.Black
    val White = Color.White
    val Transparent = Color.Transparent
}
